#!/usr/bin/env python3
"""Generates Packages/OxideKit/Sources/OxideKit/KeyCodes.swift from rdev's key tables.

RustDesk's "map" keyboard mode sends each key as the host platform's own key
code. Its iOS and Android clients convert USB HID usages with rdev's
usb_hid_code_to_{win_scancode,macos_code,macos_iso_code,linux_code}; this
reproduces those conversions as lookup tables.

Usage: tools/gen_keycodes.py <path to rustdesk-org/rdev checkout>
Tables generated from rdev 0904f23 (the commit RustDesk 1.5.3 pins). rdev is MIT licensed.
"""
import re
import sys
from pathlib import Path


def entries(path: Path, fields: int) -> list[list[str]]:
    """The rows of the file's decl_keycodes! table, in order."""
    text = path.read_text()
    start = re.search(r"^decl_keycodes!\s*[({]", text, re.M)
    body = text[start.end():]
    body = body[: re.search(r"^[)}]", body, re.M).start()]
    body = re.sub(r"//[^\n]*", "", body)
    tokens = [t.strip() for t in body.split(",") if t.strip()]
    assert len(tokens) % fields == 0, path
    return [tokens[i:i + fields] for i in range(0, len(tokens), fields)]


def number(s: str) -> int:
    return int(s, 16) if s.lower().startswith("0x") else int(s)


def main(rdev: Path) -> None:
    codes = rdev / "src" / "keycodes"
    # Rust `match` takes the first arm, so the first row for a code or key wins.
    hid_to_key: dict[int, str] = {}
    for key, code in entries(codes / "usb_hid.rs", 2):
        hid_to_key.setdefault(number(code), key)

    win: dict[str, int] = {}
    for key, _vk, scancode in entries(codes / "windows.rs", 3):
        win.setdefault(key, number(scancode))

    linux: dict[str, int] = {}
    for key, code in entries(codes / "linux.rs", 2):
        linux.setdefault(key, number(code))

    consts = {
        m.group(1): number(m.group(2))
        for m in re.finditer(r"pub const (kVK_\w+): CGKeyCode = (\w+);", (codes / "macos_virtual_keycodes.rs").read_text())
    }
    mac: dict[str, int] = {}
    for key, name in entries(codes / "macos.rs", 2):
        mac.setdefault(key, consts[name])
    # codes_conv.rs: macos_target_code_from_key, macos_iso_code_from_key.
    mac["NonConvert"] = consts["kVK_JIS_Eisu"]
    mac["Convert"] = consts["kVK_JIS_Kana"]
    # (rdev also has an ISO variant that swaps § and `; the official client picks it by a
    # user setting. Oxide uses the ANSI codes.)

    def table(name: str, lookup) -> str:
        rows = []
        for hid in sorted(hid_to_key):
            key = hid_to_key[hid]
            code = lookup(key)
            if code is not None:
                rows.append(f"        0x{hid:02X}: 0x{code:X},  // {key}")
        return f"    static let {name}: [Int: Int32] = [\n" + "\n".join(rows) + "\n    ]\n"

    out = [
        "// Generated by tools/gen_keycodes.py from rdev (MIT, github.com/rustdesk-org/rdev,",
        "// commit 0904f23). Do not edit by hand.",
        "",
        "/// USB HID keyboard usages to each host platform's key codes, as RustDesk's",
        "/// mobile clients convert them for map mode.",
        "enum KeyCodes {",
        "    /// Windows set-1 scan codes; extended keys carry 0xE0 in the high byte.",
        # Pause has no scan code (0): the official client sends it as a legacy key.
        table("windows", lambda k: win.get(k) or None),
        "    /// macOS virtual key codes (ANSI layout).",
        table("macOS", mac.get),
        "    /// X11 key codes (evdev + 8).",
        table("linux", linux.get),
        "}",
        "",
    ]
    target = Path(__file__).resolve().parent.parent / "Packages/OxideKit/Sources/OxideKit/KeyCodes.swift"
    target.write_text("\n".join(out))
    print(f"wrote {target}: {len(hid_to_key)} HID usages")


if __name__ == "__main__":
    main(Path(sys.argv[1]))
